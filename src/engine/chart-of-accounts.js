/**
 * Registre des sous-comptes créés en cours de session (port de
 * FM_PLAN[compte] = label de l'appli d'origine). Le SYSCOHADA autorise la
 * subdivision des comptes collectifs (401, 411…) : un sous-compte est
 * accepté ssi son plus long préfixe existe au plan officiel et qu'il fait
 * 4 à 6 chiffres. Le registre est rechargé depuis `fm_settings` (clé
 * `tiers`) à chaque connexion — 100 % cloud, zéro localStorage.
 * Le sens normal est hérité du compte parent.
 */
const SUB_ACCOUNTS = {};

export function registerSubAccount(numero, intitule) {
  const n = String(numero || '');
  if (!/^\d{4,6}$/.test(n)) return false;
  if (ACCOUNTS[n] || SUB_ACCOUNTS[n]) return false; // déjà connu
  let parent = null;
  for (let len = n.length - 1; len >= 2; len--) {
    const p = n.slice(0, len);
    if (ACCOUNTS[p]) { parent = p; break; }
  }
  if (!parent) return false; // aucun compte parent au plan
  SUB_ACCOUNTS[n] = {
    intitule: String(intitule || '').slice(0, 80) || ('Sous-compte ' + n),
    sens: ACCOUNTS[parent].sens || '',
  };
  return true;
}

/** Vrai si le compte est un sous-compte enregistré (non officiel). */
export function isSubAccount(numero) { return !!SUB_ACCOUNTS[String(numero || '')]; }

/** Réinitialise le registre (tests). */
export function clearSubAccounts() {
  Object.keys(SUB_ACCOUNTS).forEach((k) => delete SUB_ACCOUNTS[k]);
}

export function classOf(numero) { return String(numero || '').charAt(0) || ''; }

export function accountsByClass(classe) {
  const k = String(classe);
  return Object.keys(ACCOUNTS).filter(n => n.charAt(0) === k).sort();
}
