/** Sens normal d'un compte : 'D', 'C' ou '' (mixte/indéterminé). */
export function sensNormal(compte) {
  const c = String(compte || '');
  const f = c.charAt(0);
  if (f === '2' || f === '3' || f === '6') return 'D';
  if (f === '1' || f === '7' || f === '8') return 'C';
  if (SENS_MAP[c]) return SENS_MAP[c];
  for (let n = c.length - 1; n >= 2; n--) { const p = c.slice(0, n); if (SENS_MAP[p]) return SENS_MAP[p]; }
  return '';
}

export function getAccount(numero) {
  const n = String(numero || '');
  const a = ACCOUNTS[n] || SUB_ACCOUNTS[n];
  return a ? { numero: n, intitule: a.intitule, classe: n.charAt(0), sens: a.sens } : null;
}

export function isValidAccount(numero) { return getAccount(numero) !== null; }

